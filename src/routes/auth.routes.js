const { Router } = require("express");
const controller = require("../controllers/auth.controller");
const { requireAuth } = require("../middlewares/auth.middleware");
const emailRateLimit = require("../middlewares/emailRateLimit.middleware");
const router = Router();
router.post("/email/otp/request", emailRateLimit, controller.requestLoginOtp);
router.post("/email/otp/verify", emailRateLimit, controller.verifyLoginOtp);
router.post("/refresh", controller.refresh);
router.post("/logout", controller.logout);
router.post("/phone/send-code", controller.sendPhoneCode);
router.post("/phone/verify-code", controller.verifyPhoneCode);
router.get("/me", requireAuth, controller.me);
router.patch("/me", requireAuth, controller.updateProfile);
module.exports = router;
