const { Router } = require("express");
const controller = require("../controllers/auth.controller");
const { requireAuth } = require("../middlewares/auth.middleware");
const emailRateLimit = require("../middlewares/emailRateLimit.middleware");
const router = Router();
router.post("/register", controller.register);
router.post("/login", controller.login);
router.post("/refresh", controller.refresh);
router.post("/logout", controller.logout);
router.post("/forgot-password", emailRateLimit, controller.forgotPassword);
router.post("/forgot-password/verify", emailRateLimit, controller.verifyPasswordReset);
router.post("/reset-password", emailRateLimit, controller.resetPassword);
router.post("/email/send-verification", emailRateLimit, controller.sendVerification);
router.post("/email/verify", emailRateLimit, controller.verifyEmail);
router.post("/phone/send-code", controller.sendPhoneCode);
router.post("/phone/verify-code", controller.verifyPhoneCode);
router.post("/google", controller.google);
router.get("/me", requireAuth, controller.me);
router.patch("/me", requireAuth, controller.updateProfile);
module.exports = router;
